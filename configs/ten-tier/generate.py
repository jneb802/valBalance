"""Generate reviewable Fortress fragments. Never writes to a game profile."""
import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent


def generate():
    source = ROOT / 'workshops/star-only/summary.json'
    summary = json.loads(source.read_text())
    design = yaml.safe_load((ROOT / 'workshops/star-only/design.yaml').read_text())
    tributes = ['Resin', 'Guck', 'Crystal', 'BlackMetal', 'SeekerMeat',
                'Softtissue', 'CharredBone', 'SealBlubber', 'Amber', 'Ruby']
    biomes = ['BlackForest', 'Swamp', 'Mountain', 'Plains', 'Mistlands',
              'Mistlands', 'AshLands', 'DeepNorth', 'DeepNorth', 'DeepNorth']
    spawn_types = {'normal': 'common', 'magic': 'rare', 'rare': 'elite', 'unique': 'unique'}
    creatures, levels, index = {}, [], []
    for event, definition in design['events'].items():
        tier = definition['tier']
        entries = [r for r in summary['creatures'] if r['event'] == event]
        aliases, rules = [], []
        for entry in entries:
            alias = f"VB10_T{tier:02d}_{entry['prefab']}"
            rarity = entry['rarity']
            cost = 100 if rarity == 'unique' else 10
            if tier == 1:
                cost = {'normal': 6, 'magic': 20, 'rare': 20, 'unique': 100}[rarity]
            elif tier == 3 and rarity == 'normal':
                cost = 13
            creatures[alias] = dict(spawnCost=cost, prefabName=entry['prefab'],
                                    spawnType=spawn_types[rarity], biome=biomes[tier-1],
                                    enabled=True, dropsEnabled=False)
            aliases.append(alias)
            rules.append(dict(creatures=[alias], minStars=entry['stars'], maxStars=entry['stars']))
        count = sum(definition['waves']['regular'].values()) + sum(definition['waves']['finale_addition'].values())
        levels.append(dict(tributeName=tributes[tier-1], tributeAmount=10,
                           rewards=dict(DustRare=10, EssenceRare=10, ReagentRare=10),
                           hardMode=False, siegeMode=False,
                           wildshrineWaveStartLocalization=f"Tier {tier}: {event.replace('_', ' ')}.",
                           wildshrineWaveEndLocalization=f"Tier {tier} complete.",
                           wildLevelDefinition=dict(levelIndex=1, biome=biomes[tier-1],
                               waveFormat='DynamicBoss' if tier == 1 else 'CommonOnly',
                               levelWarningLocalization='Four waves. The final boss arrives in wave four.',
                               maxCreaturesPerPhaseOverride=count, onlySelectMonsters=aliases,
                               commonSpawnModifiers={}, rareSpawnModifiers={}, eliteSpawnModifiers={},
                               creatureRules=rules)))
        index.append(dict(tier=tier, event=event, tribute=tributes[tier-1], amount=10,
                          regular_count=count-1, final_count=count, aliases=aliases))
    wave_styles = {'CommonOnly': {'waveFormats': [
        {'spawnType': 'common', 'spawnPercentage': 45},
        {'spawnType': 'rare', 'spawnPercentage': 25},
        {'spawnType': 'elite', 'spawnPercentage': 15},
        {'spawnType': 'unique', 'spawnPercentage': 100}]},
        'DynamicBoss': {'waveFormats': [
        {'spawnType': 'unique', 'spawnPercentage': 100},
        {'spawnType': 'elite', 'spawnPercentage': 20},
        {'spawnType': 'rare', 'spawnPercentage': 20},
        {'spawnType': 'rare', 'spawnPercentage': 20},
        {'spawnType': 'common', 'spawnPercentage': 20},
        {'spawnType': 'common', 'spawnPercentage': 20}]}}
    documents = {
        'SpawnableCreatures.fragment.yaml': {'creatures': creatures},
        'WaveStyles.fragment.yaml': {'waveFormats': wave_styles},
        'WildShrines.fragment.yaml': {'wildShrines': [dict(
            definitionForWildShrine='VF_wild_shrine_yellow1', wildShrineLevelsConfig=levels)]},
        'UnrelatedLevels.exclusions.yaml': {'excludeSelectMonsters': list(creatures)},
        'index.yaml': {'status': 'Config draft; not deployed or live validated',
                       'summary_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                       'required_base_challenge_points': 100, 'events': index}}
    for name, document in documents.items():
        (HERE / name).write_text('# Generated by configs/ten-tier/generate.py. See README.md before merging.\n' +
                                 yaml.safe_dump(document, sort_keys=False))
    return documents


if __name__ == '__main__':
    generate()
